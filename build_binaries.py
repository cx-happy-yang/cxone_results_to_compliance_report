"""Build a self-contained cxone-pci-report binary with PyInstaller.

Produces ``dist/cxone-pci-report-<version>-<os>-<arch>[.exe]`` for the
current platform, e.g. ``cxone-pci-report-0.1.0-windows-x64.exe``.

Usage (from the repo root)::

    pip install ".[build]"
    python build_binaries.py
"""

import platform
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent
PACKAGE_DIR = REPO_ROOT / "cxone_pci_report"
ASSETS_DIR = PACKAGE_DIR / "assets"
DIST_DIR = REPO_ROOT / "dist"
BUILD_DIR = REPO_ROOT / "build"

_OS_NAMES = {"win32": "windows", "darwin": "macos", "linux": "linux"}
_ARCH_NAMES = {
    "x86_64": "x64",
    "amd64": "x64",
    "aarch64": "arm64",
    "arm64": "arm64",
}


def target_platform() -> tuple[str, str]:
    """Return the ``(os, arch)`` pair for the machine we are building on."""
    os_name = _OS_NAMES.get(sys.platform)
    if os_name is None:
        raise SystemExit(
            f"ERROR: unsupported platform {sys.platform!r}; "
            f"expected win32, darwin, or linux."
        )
    arch_name = _ARCH_NAMES.get(platform.machine().lower())
    if arch_name is None:
        raise SystemExit(
            f"ERROR: unsupported architecture {platform.machine()!r}."
        )
    return os_name, arch_name


def binary_name(version: str) -> str:
    os_name, arch_name = target_platform()
    base = f"cxone-pci-report-{version}-{os_name}-{arch_name}"
    return base + (".exe" if sys.platform == "win32" else "")


def _entry_script() -> Path:
    """Write the PyInstaller entrypoint (absolute import of the CLI).

    Passing ``cxone_pci_report/__main__.py`` directly would make PyInstaller
    treat it as a standalone script and break its relative ``.cli`` import.
    """
    entry = BUILD_DIR / "pyinstaller" / "entry.py"
    entry.parent.mkdir(parents=True, exist_ok=True)
    entry.write_text(
        '"""PyInstaller entrypoint (generated by build_binaries.py)."""\n'
        "from cxone_pci_report.cli import main\n"
        "\n"
        'if __name__ == "__main__":\n'
        "    raise SystemExit(main())\n",
        encoding="utf-8",
    )
    return entry


def main() -> int:
    # Make the package importable when run from outside the repo root.
    sys.path.insert(0, str(REPO_ROOT))
    from cxone_pci_report import __version__

    name = binary_name(__version__)
    # PyInstaller --add-data uses ';' on Windows and ':' elsewhere.
    sep = ";" if sys.platform == "win32" else ":"
    command = [
        sys.executable, "-m", "PyInstaller",
        "--onefile",
        "--clean",
        "--noconfirm",
        "--name", name,
        # Destination is the path inside the bundle: builder.py resolves
        # assets relative to its own __file__, i.e. cxone_pci_report/assets.
        "--add-data", f"{ASSETS_DIR}{sep}cxone_pci_report/assets",
        # reportlab loads charts, fonts, and encodings dynamically.
        "--collect-all", "reportlab",
        "--distpath", str(DIST_DIR),
        "--workpath", str(BUILD_DIR / "pyinstaller"),
        "--specpath", str(BUILD_DIR / "pyinstaller"),
        str(_entry_script()),
    ]
    print(f"Building {name!r} with PyInstaller ...")
    try:
        subprocess.run(command, cwd=REPO_ROOT, check=True)
    except subprocess.CalledProcessError as exc:
        print(
            "ERROR: PyInstaller failed; install it with "
            'pip install ".[build]" and see the output above.',
            file=sys.stderr,
        )
        return exc.returncode

    binary = DIST_DIR / name
    if not binary.is_file():
        print(f"ERROR: expected binary not found: {binary}", file=sys.stderr)
        return 1
    print(f"Binary written: {binary}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
